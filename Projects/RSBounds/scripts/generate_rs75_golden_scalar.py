"""Generate exact finite golden-point moment certificates for Lean.

Run verification/rs75-golden-moments-diagnostic.py first. The resulting Lean
file checks every integer-root and LogCert bound with the ordinary kernel;
Python's diagnostic is not imported as a proof premise.
"""
from pathlib import Path
from fractions import Fraction as Q
import json,hashlib
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'verification/rs75-golden-moments-diagnostic.json').read_text())
assert data['generator_sha256']==hashlib.sha256((ROOT/'verification/rs75-golden-moments-diagnostic.py').read_bytes()).hexdigest()
D=data['root_scale']; LD=data['log_scale']
nodes=[];cache={}
def qs(q):
 q=Q(q);return str(q.numerator) if q.denominator==1 else f'{q.numerator}/{q.denominator}'
def qb(a,b):
 lo=sum(2*LD*b**(2*j+1)//((2*j+1)*(2*a+b)**(2*j+1)) for j in range(12))
 hi=lo+12+3*LD*b**25//(25*(2*a+b)**25)+1
 return Q(lo,LD),Q(hi,LD)
def make(op,*args):
 key=(op,*args)
 if key in cache:return cache[key]
 if op=='rat':lo=hi=Q(args[0])
 elif op=='root':
  n,p,k,b=args
  assert b**k*n**p<=D**k<=(b+1)**k*n**p
  lo,hi=Q(b,D),Q(b+1,D)
 elif op=='log':
  n=args[0];k,a,b=data['log_certificates'][n-1]
  assert 2**k*(Q(1)+Q(b,a))==n and 0<b<=a
  l,h=qb(a,b);l2,h2=qb(1,1);lo,hi=k*l2+l,k*h2+h
 elif op in ['add','sub','mul']:
  a,b=[nodes[i] for i in args]
  if op=='add':lo,hi=a['lo']+b['lo'],a['hi']+b['hi']
  elif op=='sub':lo,hi=a['lo']-b['hi'],a['hi']-b['lo']
  else:
   c=[x*y for x in [a['lo'],a['hi']] for y in [b['lo'],b['hi']]];lo,hi=min(c),max(c)
 elif op=='inv':
  a=nodes[args[0]];assert a['lo']>0;lo,hi=1/a['hi'],1/a['lo']
 elif op=='pow':
  a,n=nodes[args[0]],args[1];lo=hi=Q(1)
  for _ in range(n):
   c=[x*y for x in [lo,hi] for y in [a['lo'],a['hi']]];lo,hi=min(c),max(c)
 else:raise ValueError(op)
 i=len(nodes);nodes.append(dict(op=op,args=args,lo=lo,hi=hi));cache[key]=i;return i
def rat(q):return make('rat',Q(q))
def add(a,b):return make('add',a,b)
def sub(a,b):return make('sub',a,b)
def mul(a,b):return make('mul',a,b)
def div(a,b):return mul(a,make('inv',b))
def powi(a,j):return make('pow',a,j)
def log(n):return rat(0) if n==1 else make('log',n)
certs=[]
for row in data['point_rows']:
 p,k=row['p'],row['k'];s=Q(p,k);a=s-1
 roots=[rat(1) if n==1 else make('root',n,p,k,b) for n,b in enumerate(row['root_floor_numerators'],1)]
 for j in range(2 if p == 233 else 3):
  partial=rat(0)
  for n in range(1,64):partial=add(partial,mul(powi(log(n),j),roots[n-1]))
  L=log(64);rt=roots[63];fN=mul(powi(L,j),rt)
  if j==0:poly=div(rat(1),rat(a))
  elif j==1:poly=add(div(L,rat(a)),div(rat(1),powi(rat(a),2)))
  else:poly=add(add(div(powi(L,2),rat(a)),div(mul(rat(2),L),powi(rat(a),2))),div(rat(2),powi(rat(a),3)))
  integral=mul(mul(rat(64),rt),poly)
  center=add(add(partial,div(fN,rat(2))),integral)
  epoly=sub(mul(rat(s),powi(L,j)),mul(rat(j),powi(L,max(0,j-1))))
  err=div(mul(epoly,rt),rat(512))
  upper=add(center,err)
  certs.append((p,k,j,center,upper))

targets=[('upperPoint_zero_upper',233,144,0,'upper',Q('2.23829')),
 ('upperPoint_one_lower',233,144,1,'center',Q('2.55131')),
 ('lowerPoint_zero_lower',55,34,0,'center',Q('2.2393')),
 ('lowerPoint_zero_upper',55,34,0,'upper',Q('2.2394')),
 ('lowerPoint_one_lower',55,34,1,'center',Q('2.5547')),
 ('lowerPoint_two_upper',55,34,2,'upper',Q('8.4776'))]
header='''import RSBounds.RS75GoldenScalarBase

/-!
# Finite scalar bounds for the two rational golden-ratio endpoints

Generated by scripts/generate_rs75_golden_scalar.py. Every root/logarithm
certificate is kernel checked. These are bounds on explicit finite sums
and displayed tail expressions, not yet on zeta derivatives or infinite
moments. The analytic moment-to-tail theorem is a separate remaining task.
-/

namespace TernaryGoldbach.RSBounds.RS75GoldenNumerics
open GoldenScalar

set_option maxRecDepth 100000
set_option maxHeartbeats 0

noncomputable def momentSum (s : ℝ) (j : ℕ) : ℕ → ℝ
  | 0 => 0
  | m + 1 => momentSum s j m + Real.log (m + 1 : ℝ) ^ j * (m + 1 : ℝ) ^ (-s)

noncomputable def tailIntegral (s : ℝ) : ℕ → ℝ
  | 0 => 64 * (64 : ℝ) ^ (-s) * (1 / (s - 1))
  | 1 => 64 * (64 : ℝ) ^ (-s) * (Real.log 64 / (s - 1) + 1 / (s - 1)^2)
  | 2 => 64 * (64 : ℝ) ^ (-s) * (Real.log 64 ^ 2 / (s - 1) +
      2 * Real.log 64 / (s - 1)^2 + 2 / (s - 1)^3)
  | _ => 0

noncomputable def center (s : ℝ) (j : ℕ) : ℝ :=
  momentSum s j 63 + Real.log 64 ^ j * (64 : ℝ) ^ (-s) / 2 + tailIntegral s j

noncomputable def upper (s : ℝ) (j : ℕ) : ℝ := center s j +
  (s * Real.log 64 ^ j - (j : ℝ) * Real.log 64 ^ (j - 1)) * (64 : ℝ) ^ (-s) / 512

'''
lines=[header]
for i,n in enumerate(nodes):
 op,a=n['op'],n['args']
 if op=='rat':rhs=f'.known (.rat ({qs(a[0])}))'
 elif op=='root':rhs=f'.root {a[0]} {a[1]} {a[2]} {D} {a[3]}'
 elif op=='log':
  c=data['log_certificates'][a[0]-1];ct='⟨'+', '.join(map(str,c))+'⟩'
  rhs=f'.known (.log {ct} {ct} (.rat {a[0]}))'
 elif op in ['add','sub','mul']:rhs=f'.{op} n{a[0]} n{a[1]}'
 elif op=='inv':rhs=f'.inv n{a[0]}'
 elif op=='pow':rhs=f'.pow n{a[0]} {a[1]}'
 lines.append(f'private def n{i} : Expr := {rhs}')
def deps(i):
 n=nodes[i];ds={i}
 if n['op'] in ['add','sub','mul']:
  for j in n['args']:ds |= deps(j)
 elif n['op'] in ['inv','pow']:ds|=deps(n['args'][0])
 return ds
for name,p,k,j,side,target in targets:
 _,_,_,ce,up=next(c for c in certs if c[:3]==(p,k,j));i=ce if side=='center' else up
 if side=='center':assert target<nodes[i]['lo'];rel='<';numeric=f'({qs(target)} : ℚ) < {name}Certificate.bounds.lo';conclusion=f'({qs(target)} : ℝ) < center ({p}/{k}) {j}';method='lt_eval'
 else:assert nodes[i]['hi']<target;rel='<';numeric=f'{name}Certificate.bounds.hi < ({qs(target)} : ℚ)';conclusion=f'upper ({p}/{k}) {j} < ({qs(target)} : ℝ)';method='eval_lt'
 names=', '.join('n'+str(d) for d in sorted(deps(i)))
 lines.append(f'''\nprivate def {name}Certificate : Expr := n{i}
private theorem {name}Checked : {name}Certificate.check = true := by decide +kernel
private theorem {name}Rational : {numeric} := by decide +kernel
private theorem {name}Eval : {name}Certificate.eval = {side} ({p}/{k}) {j} := by
  norm_num [{name}Certificate, Expr.eval, QuarticBudgetNumerics.Expr.eval,
    {names}, center, upper, tailIntegral, momentSum, div_eq_mul_inv]

/-- Closed finite-expression bound only; the infinite moment binding is separate. -/
theorem {name} : {conclusion} := by
  rw [← {name}Eval]
  convert Expr.{method} {name}Checked {name}Rational using 1 <;> norm_num
''')
lines.append('end TernaryGoldbach.RSBounds.RS75GoldenNumerics\n')
(ROOT/'RSBounds/RS75GoldenNumerics.lean').write_text('\n'.join(lines))
rec={'status':'generated source; Lean compilation and axiom audit pending','nodes':len(nodes),
 'root_nodes':sum(n['op']=='root' for n in nodes),'log_nodes':sum(n['op']=='log' for n in nodes),
 'targets':[n for n,*_ in targets],'generator_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
(ROOT/'verification/rs75-golden-scalar-generated.json').write_text(json.dumps(rec,indent=2)+'\n')
print(json.dumps(rec,indent=2))
