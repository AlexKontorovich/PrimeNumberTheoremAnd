"""Generate rational witnesses for the height-50 finite zeta sum.

Floating point selects witnesses only. The generated Lean file checks all
angle, root, and aggregate inequalities by kernel reduction.
"""
from fractions import Fraction as F
from math import isqrt
from pathlib import Path
import json
import mpmath as mp

mp.mp.dps = 80
ROOT = Path(__file__).resolve().parent.parent
D = 10**6
L = 10**30
pi_lo = F(314159265358979323846, 10**20)
pi_hi = F(314159265358979323847, 10**20)
log_lo = [0, 0]
log_hi = [0, 0]
for n in range(1, 20):
    lo = sum(2*L // ((2*k+1)*(2*n+1)**(2*k+1)) for k in range(12))
    hi = lo + 12 + 3*L // (25*(2*n+1)**25) + 1
    log_lo.append(log_lo[-1] + lo)
    log_hi.append(log_hi[-1] + hi)

rows = []
totals = [F(0)] * 4
for n in range(1, 21):
    m = int(mp.nint(100*mp.log(n)/mp.pi))
    angle = 50*mp.log(n)-m*mp.pi/2
    q = F(int(mp.nint(angle*D)), D)
    b = isqrt(D*D//n)
    while b*b*n < D*D:
        b += 1
    assert -F(1,100000) <= 50*F(log_lo[n],L)-q-m*pi_hi/2
    assert 50*F(log_hi[n],L)-q-m*pi_lo/2 <= F(1,100000)
    assert abs(q) <= 1
    c = 1-q*q/2+q**4/24-q**6/720
    s = q-q**3/6+q**5/120-q**7/5040
    c, s = [(c,s),(-s,c),(-c,-s),(s,-c)][m%4]
    a, u = F(1,n), F(b,D)
    bounds = [min(a*(c-F(1,10000)),u*(c-F(1,10000))),
              max(a*(c+F(1,10000)),u*(c+F(1,10000))),
              min(a*(s-F(1,10000)),u*(s-F(1,10000))),
              max(a*(s+F(1,10000)),u*(s+F(1,10000)))]
    weight = F(1,2) if n == 20 else F(1)
    totals = [t+weight*v for t,v in zip(totals,bounds)]
    rows.append((n,m,q,b))

def rat(q):
    return str(q.numerator) if q.denominator == 1 else f"({q.numerator} / {q.denominator})"

text = '''import RSBounds.BacklundBottomCertificates

/-! Generated by `scripts/gen_backlund_bottom_data.py`; each witness is checked below. -/
set_option maxRecDepth 4096
set_option maxHeartbeats 2000000

namespace TernaryGoldbach.RSBounds.BacklundBottomCertificates

def quarterTurns : ℕ → ℕ
'''
text += "".join(f"  | {n} => {m}\n" for n,m,q,b in rows) + "  | _ => 0\n\n"
text += "def reducedAngle : ℕ → ℚ\n"
text += "".join(f"  | {n} => {rat(q)}\n" for n,m,q,b in rows) + "  | _ => 0\n\n"
text += "def amplitudeNumerator : ℕ → ℕ\n"
text += "".join(f"  | {n} => {b}\n" for n,m,q,b in rows) + "  | _ => 0\n\n"
text += '''def rowCheck (n : ℕ) : Bool :=
  angleCheck n (quarterTurns n) (reducedAngle n) &&
    decide (|reducedAngle n| ≤ 1 ∧ 10 ^ 12 ≤ (amplitudeNumerator n) ^ 2 * n)

theorem all_rows_checked : (List.range' 1 20).all rowCheck = true := by decide +kernel

def amplitudeLo (n : ℕ) : ℚ := 1 / n
def amplitudeHi (n : ℕ) : ℚ := (amplitudeNumerator n : ℚ) / 10 ^ 6

def realLo (n : ℕ) : ℚ := min
  (amplitudeLo n * (cosRot (reducedAngle n) (quarterTurns n) - 1 / 10000))
  (amplitudeHi n * (cosRot (reducedAngle n) (quarterTurns n) - 1 / 10000))
def realHi (n : ℕ) : ℚ := max
  (amplitudeLo n * (cosRot (reducedAngle n) (quarterTurns n) + 1 / 10000))
  (amplitudeHi n * (cosRot (reducedAngle n) (quarterTurns n) + 1 / 10000))
def sineLo (n : ℕ) : ℚ := min
  (amplitudeLo n * (sinRot (reducedAngle n) (quarterTurns n) - 1 / 10000))
  (amplitudeHi n * (sinRot (reducedAngle n) (quarterTurns n) - 1 / 10000))
def sineHi (n : ℕ) : ℚ := max
  (amplitudeLo n * (sinRot (reducedAngle n) (quarterTurns n) + 1 / 10000))
  (amplitudeHi n * (sinRot (reducedAngle n) (quarterTurns n) + 1 / 10000))

def weight (n : ℕ) : ℚ := if n = 20 then 1 / 2 else 1

theorem aggregate_checked :
    -(127 / 100 : ℚ) ≤ ∑ n ∈ Finset.Icc 1 20, weight n * realLo n ∧
    (∑ n ∈ Finset.Icc 1 20, weight n * realHi n) ≤ 159 / 100 ∧
    -(125 / 100 : ℚ) ≤ ∑ n ∈ Finset.Icc 1 20, weight n * sineLo n ∧
    (∑ n ∈ Finset.Icc 1 20, weight n * sineHi n) ≤ 125 / 100 := by decide +kernel

end TernaryGoldbach.RSBounds.BacklundBottomCertificates
'''
(ROOT/"RSBounds/BacklundBottomData.lean").write_text(text)
record = {"kind":"witness-generation-only-not-a-Lean-proof",
          "aggregate_bounds_decimal":[str(mp.mpf(t.numerator)/t.denominator) for t in totals],
          "rows":[{"n":n,"quarter_turns":m,"angle":str(q),"amplitude_numerator":b}
                  for n,m,q,b in rows]}
(ROOT/"verification/backlund-bottom-witnesses.json").write_text(json.dumps(record,indent=2)+"\n")
print(json.dumps({"aggregate_bounds_decimal":record["aggregate_bounds_decimal"]},indent=2))
