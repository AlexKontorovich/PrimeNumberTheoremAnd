#!/usr/bin/env python3
"""Write RSBounds/PsiFinite/BasePrimes.lean: the odd primes up to 10^5.

Untrusted: the Lean module PsiFinite.BaseCert re-derives the list by a
kernel-checked sieve. Run from Projects/RSBounds:
    python3 -I tools/psi_planner/gen_base_primes.py
"""
N = 100000
s = bytearray([1]) * (N + 1)
s[0] = s[1] = 0
for i in range(2, 317):
    if s[i]:
        s[i * i::i] = bytearray(len(s[i * i::i]))
ps = [p for p in range(3, N + 1) if s[p]]
assert len(ps) == 9591 and ps[-1] == 99991
lines = ['  ' + ', '.join(map(str, ps[i:i + 20])) for i in range(0, len(ps), 20)]
src = '''/-!
# Odd primes up to 10^5

`basePrimes` lists the 9591 odd primes below 10^5 in increasing order. It is
generated by `tools/psi_planner/gen_base_primes.py`. Nothing here is trusted:
`PsiFinite.BaseCert` proves, with kernel-checked sieving, that the list consists
of exactly the odd primes up to 10^5.

This module does not import Mathlib.
-/

namespace PsiFinite

set_option maxRecDepth 100000 in
/-- The odd primes `3 ≤ p ≤ 99991`, increasing. -/
def basePrimes : List Nat := [
''' + ',\n'.join(lines) + '''
]

end PsiFinite
'''
with open('RSBounds/PsiFinite/BasePrimes.lean', 'w') as f:
    f.write(src)
